#!/usr/bin/env python3
"""gen-lazyvk.py - regenerate the lazyvk trampoline tables.

Parses `nm -D --defined-only` of the real hybris Vulkan loader and emits:

  lazyvk/lazyvk.c - one pointer slot per entrypoint + the vk_ents[] table
  lazyvk/lazyvk.S - one register-preserving tail-call stub per entrypoint

The runtime (dlopen + dlsym fill, constructor, unresolved handler) lives in
lazyvk/runtime.c and is NOT generated.  Entry points the loader does not
provide but that clients link against (see lazyvk/extra_symbols.txt) are
emitted as NULL slots, so such binaries still load.

Usage: gen-lazyvk.py [--real <loader>] [--out-dir <lazyvk dir>]
Idempotent; run by scripts/make-vk-libs.sh before compiling the shim.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

# The hybris part root (scripts/ lives directly under it), so the generator
# works from any checkout location.
PROJ = Path(__file__).resolve().parent.parent
ENTRY_RE = re.compile(r"^vk[A-Z]")


def loader_entrypoints(real: Path) -> list[str]:
    out = subprocess.run(
        ["nm", "-D", "--defined-only", str(real)],
        check=True, capture_output=True, text=True,
    ).stdout
    names = set()
    for line in out.splitlines():
        parts = line.split()
        if len(parts) != 3:
            continue
        _, kind, name = parts
        # T = plain function, i = ifunc trampoline (all Vulkan entrypoints),
        # W/w = weak alias just in case.  Anything else (B/D data) is skipped.
        if kind in ("T", "i", "W", "w") and ENTRY_RE.match(name):
            names.add(name)
    return sorted(names)


def extra_entrypoints(path: Path) -> list[str]:
    if not path.is_file():
        return []
    names = []
    for line in path.read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            names.append(line)
    return sorted(set(names))


def render_c(names: list[str]) -> str:
    lines = [
        "/* auto-generated by scripts/gen-lazyvk.py - do not edit",
        " * (runtime lives in lazyvk/runtime.c, stubs in lazyvk/lazyvk.S) */",
        '#include "lazyvk.h"',
        "",
    ]
    lines += [f"void *vk_ptr_{n} = 0;" for n in names]
    lines += ["", "struct vkent vk_ents[] = {"]
    lines += [f'  {{"{n}", &vk_ptr_{n}}},' for n in names]
    lines += ["  {0, 0}", "};", ""]
    return "\n".join(lines)


def render_asm(names: list[str]) -> str:
    lines = ["/* auto-generated by scripts/gen-lazyvk.py - do not edit",
             " * tail-call stubs preserving all arg registers */"]
    for n in names:
        lines += [
            f".globl {n}",
            f".type {n}, %function",
            f"{n}:",
            f"    ldr x16, =vk_ptr_{n}",
            "    ldr x16, [x16]",
            "    cbz x16, 1f",
            "    br x16",
            "1:  b __lazyvk_unresolved",
            f".size {n}, .-{n}",
        ]
    return "\n".join(lines) + "\n"


def write(path: Path, content: str) -> None:
    tmp = path.with_suffix(path.suffix + ".new")
    tmp.write_text(content)
    tmp.replace(path)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--real", default=str(PROJ / "vk-libs/libvulkan-hybris.so.1"))
    ap.add_argument("--out-dir", default=str(PROJ / "lazyvk"))
    args = ap.parse_args()

    real = Path(args.real)
    if not real.exists():
        print(f"gen-lazyvk: real loader {real} missing", file=sys.stderr)
        return 1
    out = Path(args.out_dir)

    names = loader_entrypoints(real)
    extra = extra_entrypoints(out / "extra_symbols.txt")
    merged = sorted(set(names) | set(extra))

    write(out / "lazyvk.c", render_c(merged))
    write(out / "lazyvk.S", render_asm(merged))
    print(f"gen-lazyvk: {len(names)} loader entrypoints "
          f"(+{len(extra)} extra) -> lazyvk.c / lazyvk.S")
    return 0


if __name__ == "__main__":
    sys.exit(main())
